"""Minimal, dependency-free AES-128 (ECB mode, PKCS#7 padding).

Campus portals that encrypt credentials client-side almost always use
CryptoJS defaults: ``AES.encrypt(text, key, {mode: ECB, padding: Pkcs7})``.
This module reproduces exactly that, so the tool needs no third-party crypto
library on any platform.

Only the forward direction is implemented, which is all a login needs.
"""

