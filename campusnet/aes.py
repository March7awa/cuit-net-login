RCON = (0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36)


def _xtime(a: int) -> int:
    a <<= 1
    if a & 0x100:
        a ^= 0x11B
    return a & 0xFF


def _mul(a: int, b: int) -> int:
    """Multiply two GF(2^8) elements."""
    r = 0
    while b:
        if b & 1:
            r ^= a
        a = _xtime(a)
        b >>= 1
    return r & 0xFF


def _expand_key(key: bytes) -> list[list[int]]:
    if len(key) != 16:
        raise ValueError(f"AES-128 needs a 16-byte key, got {len(key)}")
    w = [list(key[i * 4:i * 4 + 4]) for i in range(4)]
    for i in range(4, 44):
        t = list(w[i - 1])
        if i % 4 == 0:
            t = t[1:] + t[:1]                       # RotWord
            t = [SBOX[b] for b in t]                # SubWord
            t[0] ^= RCON[i // 4 - 1]
        w.append([w[i - 4][j] ^ t[j] for j in range(4)])
    return w


def _shift_rows(s: list[int]) -> list[int]:
    # state is flat, index = 4*column + row
    out = list(s)
    for r in range(1, 4):
        row = [s[4 * c + r] for c in range(4)]
        row = row[r:] + row[:r]                     # rotate left by r
        for c in range(4):
            out[4 * c + r] = row[c]
    return out


def _mix_columns(s: list[int]) -> list[int]:
    out = list(s)
    for c in range(4):
        i = 4 * c
        a0, a1, a2, a3 = s[i], s[i + 1], s[i + 2], s[i + 3]
        out[i] = _mul(a0, 2) ^ _mul(a1, 3) ^ a2 ^ a3
        out[i + 1] = a0 ^ _mul(a1, 2) ^ _mul(a2, 3) ^ a3
        out[i + 2] = a0 ^ a1 ^ _mul(a2, 2) ^ _mul(a3, 3)
        out[i + 3] = _mul(a0, 3) ^ a1 ^ a2 ^ _mul(a3, 2)
    return out


def _encrypt_block(block: bytes, rk: list[list[int]]) -> bytes:
    s = list(block)

    def add_round_key(rnd: int) -> None:
        for c in range(4):
            for r in range(4):
                s[4 * c + r] ^= rk[4 * rnd + c][r]

    add_round_key(0)
    for rnd in range(1, 10):
        s = [SBOX[b] for b in s]
        s = _shift_rows(s)
        s = _mix_columns(s)
        add_round_key(rnd)
    s = [SBOX[b] for b in s]
    s = _shift_rows(s)
    add_round_key(10)
    return bytes(s)


def pkcs7_pad(data: bytes, block_size: int = 16) -> bytes:
    pad = block_size - (len(data) % block_size)
    return data + bytes([pad]) * pad


def aes_ecb_encrypt(key: bytes, plaintext: bytes) -> bytes:
    """Raw AES-128-ECB encryption with PKCS#7 padding."""
    rk = _expand_key(key)
    data = pkcs7_pad(plaintext)
    return b"".join(_encrypt_block(data[i:i + 16], rk) for i in range(0, len(data), 16))


def encrypt_cryptojs_style(b64_key: str, text: str) -> str:
    """Reproduce ``CryptoJS.AES.encrypt(text, enc.Base64.parse(b64_key),
    {mode: ECB, padding: Pkcs7}).toString()``.

    Returns the Base64 ciphertext exactly as CryptoJS would.
    """
    import base64

    key = base64.b64decode(b64_key)
    ct = aes_ecb_encrypt(key, text.encode("utf-8"))
    return base64.b64encode(ct).decode("ascii")
